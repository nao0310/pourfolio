const byId = new Map(GLOSSARY.map((t) => [t.id, t]));

/** 用語を id で引く（なければ null） */
export const termById = (id) => byId.get(id) ?? null;

/** 辞典の項目へのリンク先 */
export const termHref = (id) => `glossary.html#t-${id}`;

/** 区分ごとに並べた用語 */
export function glossaryByGroup() {
  return GLOSSARY_GROUPS.map((g) => ({ ...g, terms: GLOSSARY.filter((t) => t.group === g.key) }));
}

/** 言葉（別名も含む）から用語を探す。完全一致だけ */
export function findTerm(word) {
  const w = String(word ?? '').trim();
  if (!w) return null;
  return GLOSSARY.find((t) => t.word === w || (t.aliases ?? []).includes(w)) ?? null;
}
