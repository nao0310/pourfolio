const KEYS = Object.keys(ORIGIN_POINTS).sort((a, b) => b.length - a.length);
const norm = (s) => String(s ?? '').normalize('NFKC').replace(/[\s・･]/g, '');

/**
 * 産地の言葉から位置を探す（全角・半角・空白・中黒を無視。言葉の中に国の名前があれば当てる。長い名前が先）
 * @returns {[number, number]|null}
 */
export function originPoint(country) {
  const s = norm(country);
  if (!s) return null;
  if (ORIGIN_POINTS[s]) return ORIGIN_POINTS[s];
  const k = KEYS.find((key) => s.includes(key));
  return k ? ORIGIN_POINTS[k] : null;
}
