export const MAP_H = (MAP_LAT[0] - MAP_LAT[1]) * MAP_Y_SCALE;
/** コーヒーベルト（北回帰線〜南回帰線） */
export const BELT_LAT = 23.4;

/** [経度, 緯度] → 地図の上の {x, y}（左上が 0,0） */
export function project([lon, lat]) {
  return { x: Math.round((lon - MAP_LON[0]) * 10) / 10, y: Math.round((MAP_LAT[0] - lat) * MAP_Y_SCALE * 10) / 10 };
}

